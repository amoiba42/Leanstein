"""Build `docs/code_shapes.md`: real before/after pairs from the study logs (no model calls, no Lean).

Each case is a `main` run of condition C that was verified although the family's reference implementation is
NOT provable by the frozen portfolio (a *shaping* success), on an instance and seed where B failed. For each case
the catalogue shows the bug, the reference, C's verified code, the portfolio entry that closed the proof and what
B did on the same instance and seed. Selection is deterministic: one case per family, short code first,
round-robin over closing entries so that different tactics appear.

    uv run python scripts/code_shapes_catalogue.py [--n 15]
"""
from __future__ import annotations

import argparse
import gzip
import json
import sys
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from prl.analysis.features import features  # noqa: E402
from prl.config import PATHS, read_json  # noqa: E402
from prl.lean.portfolio import load_portfolio  # noqa: E402
from prl.tasks import regions as R  # noqa: E402
from prl.tasks.verina import Family  # noqa: E402

SHAPE_NAMES = {"any_recursion": "recursion", "uses_match": "`match`", "array_index_bang": "`a[i]!` indexing",
               "nat_int_cast": "Nat/Int casts", "imperative_loop": "imperative loop", "fold": "fold",
               "list_combinators": "list combinators", "uses_if": "`if`"}


def lines(path: Path):
    gz = path.with_name(path.name + ".gz")
    f = open(path, encoding="utf-8") if path.exists() else gzip.open(gz, "rt", encoding="utf-8")
    with f:
        for ln in f:
            if ln.strip():
                yield json.loads(ln)


def shape_diff(fam: Family, ref: tuple[str, str], new: tuple[str, str]) -> str:
    a = features(fam.fn, ref[0], ref[1], fam.signature.params)
    b = features(fam.fn, new[0], new[1], fam.signature.params)
    gone = [SHAPE_NAMES[k] for k in SHAPE_NAMES if a[k] and not b[k]]
    came = [SHAPE_NAMES[k] for k in SHAPE_NAMES if b[k] and not a[k]]
    parts = []
    if gone:
        parts.append("drops " + ", ".join(gone))
    if came:
        parts.append("adds " + ", ".join(came))
    return "; ".join(parts) or "same features, different formulation"


def block(code: str, lang: str = "lean") -> str:
    return f"```{lang}\n{code.strip(chr(10))}\n```"


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--n", type=int, default=15)
    a = ap.parse_args()
    pf = load_portfolio()
    scripts = {t["id"]: t["script"] for t in pf.templates}
    runs = list(lines(ROOT / "runs" / "main" / "runs.jsonl"))
    by_key = {(r["model"], r["condition"], r["instance_id"], r["seed"]): r for r in runs}
    cands = []
    for r in runs:
        if not (r["condition"] == "C" and r["success"] and r["ref_auto"] is False
                and r["kind"] in ("natural", "mutant") and r["model"] in ("qwen3.5-4b", "qwen3.5-2b")):
            continue
        b = by_key.get((r["model"], "B", r["instance_id"], r["seed"]))
        if b is None or b["success"]:
            continue
        size = len(r.get("final_code") or "") + len(r.get("final_code_aux") or "")
        if size > 900:
            continue
        cands.append((r, b, size))
    # one per family (prefer 4B, then shortest), then round-robin over closing entries
    best: dict[str, tuple] = {}
    for c in sorted(cands, key=lambda c: (c[0]["model"] != "qwen3.5-4b", c[2], c[0]["run_id"])):
        best.setdefault(c[0]["family_id"], c)
    groups = defaultdict(list)
    for c in sorted(best.values(), key=lambda c: (c[2], c[0]["family_id"])):
        groups[(c[0]["closing_entry"] or "?").split("@")[0]].append(c)
    chosen = []
    while len(chosen) < a.n and any(groups.values()):
        for k in sorted(groups, key=lambda k: (-len(groups[k]), k)):
            if groups[k] and len(chosen) < a.n:
                chosen.append(groups[k].pop(0))
    chosen.sort(key=lambda c: c[0]["family_id"])
    # B's last attempt (proof text) for the chosen runs
    want = {c[1]["run_id"] for c in chosen}
    last_b: dict[str, dict] = {}
    for at in lines(ROOT / "runs" / "main" / "attempts.jsonl"):
        if at["run_id"] in want:
            last_b[at["run_id"]] = at
    inst_dir = PATHS.data / "instances" if hasattr(PATHS, "data") else ROOT / "data" / "instances"
    out = ["# Code shapes: before/after cases from the study", "",
           f"{len(chosen)} real cases from the confirmatory study `main`, generated by "
           "`scripts/code_shapes_catalogue.py` from `runs/main/` (nothing is edited by hand). Each is a run of "
           "**C** that was verified although the family's *reference* implementation is **not** provable by the "
           "frozen portfolio, so the verified code had to take a different, automation-friendly shape. On the same "
           "instance and seed, **B** (the model writes code and proof, with feedback) failed. For each case: the "
           "injected bug, the reference, C's verified code, the portfolio entry that closed the locked theorem, "
           "and what B did. `{F}`, `{P}`, `{Q}`, `{H}` in a tactic are filled with the function, precondition, "
           "postcondition and helper names.", "",
           "Summary of what changes (features as in RQ4, `prl/analysis/features.py`):", "",
           "| # | family | model | bug | closing entry | shape change vs reference | B's outcome |",
           "|---|---|---|---|---|---|---|"]
    body = []
    shape_args: list = []
    for i, (r, b, _) in enumerate(chosen, 1):
        fam = Family.from_json(read_json(PATHS.families / f"{r['family_id']}.json"))
        inst = read_json(inst_dir / f"{r['instance_id']}.json")
        ref = (R.region_text(fam.template, "code_aux"), R.region_text(fam.template, "code"))
        new = (r.get("final_code_aux") or "", r.get("final_code") or "")
        entry = (r["closing_entry"] or "?")
        eid = entry.split("@")[0]
        prov = inst.get("provenance", {})
        if inst["kind"] == "mutant":
            bug = f"mutant `{prov.get('operator')}`: `{prov.get('before')}` → `{prov.get('after')}`"
        else:
            bug = "natural bug (wrong implementation written by Qwen3.5-9B)"
        sd = shape_diff(fam, ref, new)
        shape_args.append((fam, ref, new))
        out.append(f"| [{i}](#case-{i}) | `{r['family_id']}` | {r['model']} | {bug.split(':')[0]} | `{eid}` | {sd} | "
                   f"{b['outcome'].replace('_', ' ')} |")
        desc = fam.description.replace("-----Description-----", "").strip().split("\n")[0].strip()[:300]
        battempt = last_b.get(b["run_id"], {})
        bproof = (battempt.get("proof") or "").strip()
        bproof = "\n".join(bproof.split("\n")[:8])
        berr = "; ".join((battempt.get("verify") or {}).get("proof_errors") or [])[:300]
        body += [f"## Case {i}", "", f"**`{r['family_id']}`**, {r['model']}, seed {r['seed']}, instance "
                 f"`{r['instance_id']}`. Task: {desc}", "", f"**Bug.** {bug}. Failing test: "
                 + (f"`{inst['witness']['input_lean']}` expected `{inst['witness']['expected']}`, got "
                    f"`{inst['witness']['actual']}`." if inst.get("witness") else "none recorded."), "",
                 "**Reference (not provable by the portfolio).**", "",
                 block((ref[0] + "\n" + ref[1]).strip()), "",
                 f"**C's verified code** (attempt {r['success_attempt_idx']}, {sd}).", "",
                 block((new[0] + "\n" + new[1]).strip()), "",
                 f"**Closed by** portfolio entry `{entry}`:", "", block(scripts.get(eid, eid)), "",
                 f"**B on the same instance and seed:** {b['outcome'].replace('_', ' ')} after {b['n_attempts']} "
                 "attempts." + (" Its last proof:" if bproof else ""), ""]
        if bproof:
            body += [block(bproof), ""]
        if berr:
            body += [f"Lean: `{berr.replace('`', '')}`", ""]
    from collections import Counter
    bo = Counter(b["outcome"].replace("_", " ") for _, b, _ in chosen)
    norec = sum("drops recursion" in shape_diff(*x) for x in shape_args)
    out += ["", f"Patterns. In {norec} of the {len(chosen)} cases C's code drops the reference's recursion, "
            "usually also its `match` and `if`, and states the result with library combinators (`filter`, "
            "`all`, `foldl`, `count`, `List.range`) that `simp`, `omega` and `grind` already handle. B's "
            "outcomes on the same instances: " + ", ".join(f"{k} {v}" for k, v in bo.most_common())
            + ". *Integrity violation* is a submission rejected by the static checks (in B mostly malformed, "
            "for example a lemma in the helper region); *correct unverified* means B's code passed every test "
            "but its proof failed. The B→C cross-evaluation (`results/crosseval.md`) measures the second case "
            "over all runs.", ""] + body
    (ROOT / "docs" / "code_shapes.md").write_text("\n".join(out) + "\n", encoding="utf-8")
    print(f"wrote docs/code_shapes.md with {len(chosen)} cases from {len(best)} eligible families")


if __name__ == "__main__":
    main()
